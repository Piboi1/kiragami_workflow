# 2. GENERATE EXPANDED KINEMATICS (OPEN HEXAGONS)
# -------------------------------------------------------------
for k in range(len(r_dep)):
    r_k, z_k, w_k, gap_k = r_dep[k], get_z(r_dep[k]), get_w(k), gap_deg[k]

    # NEW: Calculate true bridge width (union of upper and lower ribbons)
    w_prev = get_w(k-1) if k > 0 else w_k
    w_bridge = w_k + w_prev

    stagger_k = 0 if k % 2 == 0 else 22.5

    for i in range(N_cuts):
        th_c = i * 45 + stagger_k
        th_L, th_R = th_c - gap_k/2, th_c + gap_k/2

        # 1. Horizontal Bridge (Hinge) -> Now uses double-wide w_bridge
        add_strip(r_k, z_k, w_bridge, th_L, r_k, z_k, w_bridge, th_R, segs=2)

        # 2. Continuous Rim bridging gaps for Top (0) and Bottom (29)
        if k == 0 or k == len(r_dep) - 1:
            next_th_L = ((i+1) * 45 + stagger_k) - gap_k/2
            add_strip(r_k, z_k, w_bridge, th_R, r_k, z_k, w_bridge, next_th_L, segs=3)

        # 3. Diagonal Ribbons twisting down to ring k+1 (remain standard w_k width)
        if k < len(r_dep) - 1:
            r_k1, z_k1, w_k1, gap_k1 = r_dep[k+1], get_z(r_dep[k+1]), get_w(k+1), gap_deg[k+1]

            # Left twisted ribbon
            botL_R = (th_c - 22.5) + gap_k1/2
            add_strip(r_k1, z_k1, w_k1, botL_R, r_k, z_k, w_k, th_L, segs=3)

            # Right twisted ribbon
            botR_L = (th_c + 22.5) - gap_k1/2
            add_strip(r_k, z_k, w_k, th_R, r_k1, z_k1, w_k1, botR_L, segs=3)

# -------------------------------------------------------------
# 3. ADD CENTER HOLE CAP
# -------------------------------------------------------------
cap_idx = len(global_verts)
global_verts.append([0, 0, 0])  # Apex origin at Z=0

# NEW: Offset the cap radius to account for the wider apex rim
w_bridge_top = get_w(0) * 2
cap_r, cap_z = r_dep[0] - w_bridge_top/2, get_z(r_dep[0])

cap_angles = []
for i in range(N_cuts):
    th_c, next_th_c = i * 45, (i+1) * 45
    cap_angles.extend(np.linspace(th_c - gap_deg[0]/2, th_c + gap_deg[0]/2, 3)[:-1])
    cap_angles.extend(np.linspace(th_c + gap_deg[0]/2, next_th_c - gap_deg[0]/2, 4)[:-1])

for idx, th_deg in enumerate(cap_angles):
    th = math.radians(th_deg)
    global_verts.append([cap_r * math.cos(th), cap_r * math.sin(th), cap_z])

N_cap = len(cap_angles)
for idx in range(N_cap):
    next_idx = (idx + 1) % N_cap
    global_faces.append([cap_idx, cap_idx + next_idx + 1, cap_idx + idx + 1])

