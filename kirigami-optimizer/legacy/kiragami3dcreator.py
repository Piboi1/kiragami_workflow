r_dep = [r[1] for r in ring_data]
gap_deg = [r[3] for r in ring_data]
r_max = r_dep[-1]

def get_z(r): return -vertical_drop * (r / r_max)**2
def get_w(k): return (r_dep[k+1] - r_dep[k]) * kerf_factor if k < len(r_dep)-1 else (r_dep[-1] - r_dep[-2]) * kerf_factor

global_verts = []
global_faces = []

def add_strip(r1, z1, w1, th1, r2, z2, w2, th2, segs):
    """Draws a continuous quad strip connecting two coordinates."""
    idx_start = len(global_verts)
    for j in range(segs + 1):
        t = j / segs
        r, z, w = r1 + t*(r2-r1), z1 + t*(z2-z1), w1 + t*(w2-w1)
        th = math.radians(th1 + t*(th2-th1))
        global_verts.extend([[(r - w/2)*math.cos(th), (r - w/2)*math.sin(th), z],
                             [(r + w/2)*math.cos(th), (r + w/2)*math.sin(th), z]])
        if j > 0:
            v = idx_start + j * 2
            global_faces.extend([[v-2, v-1, v], [v-1, v+1, v]])

